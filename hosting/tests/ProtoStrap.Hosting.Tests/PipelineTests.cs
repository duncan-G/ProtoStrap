using Aspire.Hosting;
using Aspire.Hosting.ApplicationModel;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging.Abstractions;
using ProtoStrap.Hosting.Spec;
using ProtoStrap.Hosting.Tests.Support;

namespace ProtoStrap.Hosting.Tests;

/// <summary>
/// The protostrap-spec step writes protostrap.yaml, the way `aspire do protostrap-spec` and
/// `aspire publish` run it (docs/protostrap-aspire.md, "The generator").
/// </summary>
public class PipelineTests
{
    private static IResourceBuilder<ProtoStrapEnvironmentResource> AddEnvironment(IDistributedApplicationBuilder builder)
    {
        var protostrap = builder.AddEnvironment();
        protostrap.Resource.SourceTracerFactory = root => new ProjectDirectoryTracer(root);
        protostrap.Resource.CheckCommand = null;
        return protostrap;
    }

    private static void AddApi(IDistributedApplicationBuilder builder, FixtureRepo repo, string cpu = "500m") =>
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"))
            .PublishAsProtoStrapService(s => s.Request(cpu: cpu, memory: "512Mi").Ready(Readiness.Grpc));

    [Fact]
    public async Task AspireDoProtoStrapSpecWritesTheSpec()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo, "--step", "protostrap-spec");
        AddEnvironment(builder);
        AddApi(builder, repo);

        await using (var app = builder.Build())
        {
            await app.RunAsync(TestContext.Current.CancellationToken);
        }

        var yaml = await File.ReadAllTextAsync(repo.SpecPath, TestContext.Current.CancellationToken);
        Assert.StartsWith("# Generated by ProtoStrap.Hosting 0.1.3 from apphost/Test.AppHost.csproj.\n", yaml);
        Assert.Contains("\n  api:\n    kind: service\n", yaml);
    }

    [Fact]
    public async Task TheSpecIsWrittenOnlyWhenItChanges()
    {
        using var repo = new FixtureRepo();

        async Task<SpecResult> Write(string cpu)
        {
            var builder = TestApp.Publish(repo);
            var protostrap = AddEnvironment(builder);
            AddApi(builder, repo, cpu);
            await using var app = builder.Build();
            return await SpecStep.WriteAsync(protostrap.Resource, Model(app), Execution(app), NullLogger.Instance, TestContext.Current.CancellationToken);
        }

        await Write("500m");
        var written = File.GetLastWriteTimeUtc(repo.SpecPath);
        File.SetLastWriteTimeUtc(repo.SpecPath, written.AddMinutes(-5));
        var unchanged = File.GetLastWriteTimeUtc(repo.SpecPath);

        await Write("500m");
        Assert.Equal(unchanged, File.GetLastWriteTimeUtc(repo.SpecPath));

        await Write("750m");
        Assert.NotEqual(unchanged, File.GetLastWriteTimeUtc(repo.SpecPath));
        Assert.Contains("request: { cpu: 750m, memory: 512Mi }", await File.ReadAllTextAsync(repo.SpecPath, TestContext.Current.CancellationToken));
    }

    [Fact]
    public async Task AFailedGenerationListsEveryProblemAndWritesNothing()
    {
        using var repo = new FixtureRepo();
        repo.Write("protostrap.yaml", "# the last good spec\n");
        var builder = TestApp.Publish(repo);
        var protostrap = AddEnvironment(builder);
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"));
        builder.AddProject("worker", repo.Project("services/worker/Worker.csproj"));
        await using var app = builder.Build();

        var error = await Assert.ThrowsAsync<SpecGenerationException>(() =>
            SpecStep.WriteAsync(protostrap.Resource, Model(app), Execution(app), NullLogger.Instance, TestContext.Current.CancellationToken));

        Assert.Equal($"""
            {repo.SpecPath} wasn't written: 2 problems
              api: no PublishAsProtoStrap* call: say whether it is a service, worker, stateful component or task
              worker: no PublishAsProtoStrap* call: say whether it is a service, worker, stateful component or task
            """, error.Message);
        Assert.Equal("# the last good spec\n", await File.ReadAllTextAsync(repo.SpecPath, TestContext.Current.CancellationToken));
    }

    [Fact]
    public async Task ProtoStrapCheckRunsOnTheWrittenSpec()
    {
        using var repo = new FixtureRepo();
        var check = repo.WriteExecutable("bin/protostrap", """
            #!/bin/sh
            echo "args: $*"
            echo "protostrap.yaml: line 9: components.api.request: 500m and 512Mi doesn't fit one m7g.large VM"
            exit 1

            """);
        var builder = TestApp.Publish(repo);
        var protostrap = AddEnvironment(builder);
        protostrap.Resource.CheckCommand = check;
        AddApi(builder, repo);
        await using var app = builder.Build();

        var error = await Assert.ThrowsAsync<SpecGenerationException>(() =>
            SpecStep.WriteAsync(protostrap.Resource, Model(app), Execution(app), NullLogger.Instance, TestContext.Current.CancellationToken));

        Assert.Contains($"protostrap check failed on {repo.SpecPath}", error.Message);
        Assert.Contains($"args: check --spec {repo.SpecPath}", error.Message);
        Assert.Contains("doesn't fit one m7g.large VM", error.Message);
        // The spec stays written, so the problem can be seen in it.
        Assert.True(File.Exists(repo.SpecPath));
    }

    [Fact]
    public async Task APassingCheckIsQuiet()
    {
        using var repo = new FixtureRepo();
        var check = repo.WriteExecutable("bin/protostrap", "#!/bin/sh\necho \"protostrap.yaml: ok\"\n");
        var builder = TestApp.Publish(repo);
        var protostrap = AddEnvironment(builder);
        protostrap.Resource.CheckCommand = check;
        AddApi(builder, repo);
        await using var app = builder.Build();

        var result = await SpecStep.WriteAsync(protostrap.Resource, Model(app), Execution(app), NullLogger.Instance, TestContext.Current.CancellationToken);

        Assert.Empty(result.Problems);
    }

    [Fact]
    public void TheCheckDefaultsToProtoStrapOnThePath()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);

        var protostrap = builder.AddEnvironment();

        Assert.Equal("protostrap", protostrap.Resource.CheckCommand);
    }

    private static DistributedApplicationModel Model(DistributedApplication app) =>
        app.Services.GetRequiredService<DistributedApplicationModel>();

    private static DistributedApplicationExecutionContext Execution(DistributedApplication app) =>
        app.Services.GetRequiredService<DistributedApplicationExecutionContext>();
}
