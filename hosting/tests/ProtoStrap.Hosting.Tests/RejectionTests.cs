using Aspire.Hosting;
using Aspire.Hosting.ApplicationModel;
using ProtoStrap.Hosting.Sources;
using ProtoStrap.Hosting.Tests.Support;

namespace ProtoStrap.Hosting.Tests;

/// <summary>
/// Generation fails, listing every resource at fault, on what ProtoStrap can't run
/// (docs/protostrap-aspire.md, "What the generator rejects").
/// </summary>
public class RejectionTests
{
    [Fact]
    public async Task AServiceFromAnUpstreamImageNeedsADockerfile()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddKeycloakLike("keycloak")
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "1Gi").Ready("/health/ready"));

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
            ["keycloak: runs the upstream image quay.io/keycloak/keycloak:26.7 without a Dockerfile: ProtoStrap builds every service, worker and task, so add a Dockerfile FROM it and use AddDockerfile"],
            problems);
    }

    [Fact]
    public async Task BindMountsAreRejected()
    {
        using var repo = new FixtureRepo();
        repo.Write("services/keycloak/Dockerfile", "FROM quay.io/keycloak/keycloak:26.7\n");
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddDockerfile("keycloak", repo.PathOf("services/keycloak"))
            .WithHttpEndpoint(targetPort: 8080)
            .WithBindMount("../infra/keycloak/themes", "/opt/keycloak/themes", isReadOnly: true)
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "1Gi").Ready("/health/ready"));

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
            ["keycloak: bind mount at /opt/keycloak/themes: a replica can't mount the repository, so copy the files into the image, or make them config files with WithProtoStrapConfig"],
            problems);
    }

    [Fact]
    public async Task ContainerRuntimeArgumentsAreRejected()
    {
        using var repo = new FixtureRepo();
        repo.Write("services/keycloak/Dockerfile", "FROM quay.io/keycloak/keycloak:26.7\n");
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddDockerfile("keycloak", repo.PathOf("services/keycloak"))
            .WithHttpEndpoint(targetPort: 8080)
            .WithContainerRuntimeArgs("--add-host=host.docker.internal:host-gateway")
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "1Gi").Ready("/health/ready"));

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
            ["keycloak: WithContainerRuntimeArgs isn't supported: ProtoStrap's agent starts every container the same way"],
            problems);
    }

    [Fact]
    public async Task ExecutablesMustBeExcludedFromPublish()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddExecutable("dev-operators", "bash", "../scripts", "seed-dev-operators.sh");

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
            ["dev-operators: AddExecutable runs a process on the AppHost's machine: exclude it from publish with ExcludeFromManifest(), or don't add it in publish mode"],
            problems);
    }

    [Fact]
    public async Task ReplicasAreSetByScale()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"))
            .WithReplicas(3)
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "512Mi").Ready(Readiness.Grpc));

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(["api: WithReplicas(3) isn't supported: Scale(min: ..., max: ...) sets how many replicas run"], problems);
    }

    [Fact]
    public async Task AGeneratedDockerfileIsntInTheRepository()
    {
        using var repo = new FixtureRepo();
        repo.Write("clients/web/package.json", """{ "name": "web", "scripts": { "start": "node server.js" } }""");
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddJavaScriptApp("web", repo.PathOf("clients/web"))
            .WithHttpEndpoint(targetPort: 3000, env: "PORT")
            .PublishAsProtoStrapService(s => s.Request(cpu: "250m", memory: "256Mi").Ready("/healthz"));

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
            ["web: its Dockerfile is generated by Aspire when it publishes, so it isn't in the repository: add a Dockerfile to clients/web and use AddDockerfile"],
            problems);
    }

    [Fact]
    public async Task EveryProblemIsListedTogether()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"))
            .WithReplicas(2);
        builder.AddContainer("cache", "redis", "latest")
            .WithEndpoint(targetPort: 6379, name: "tcp")
            .PublishAsProtoStrapStateful(s => s.Vm("data-1").Request(cpu: "500m", memory: "1Gi").Volume(size: "5Gi", path: "/data"));
        builder.AddExecutable("seed", "bash", ".", "seed.sh");

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
        [
            "api: no PublishAsProtoStrap* call: say whether it is a service, worker, stateful component or task",
            "cache: image redis:latest must be pinned to a tag other than latest, or a digest",
            "seed: AddExecutable runs a process on the AppHost's machine: exclude it from publish with ExcludeFromManifest(), or don't add it in publish mode",
        ], problems);
    }
}

public class GlobalJsonRejectionTests
{
    private static IDistributedApplicationBuilder TwoProjects(FixtureRepo repo)
    {
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"))
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "512Mi").Ready(Aspire.Hosting.Readiness.Grpc));
        builder.AddProject("worker", repo.Project("services/worker/Worker.csproj", "Microsoft.NET.Sdk.Worker"))
            .PublishAsProtoStrapWorker(w => w.Request(cpu: "500m", memory: "512Mi"));
        return builder;
    }

    [Fact]
    public async Task AProjectNeedsAGlobalJson()
    {
        // Without one, the deploy workflow would have to pick an SDK, and a new .NET would
        // need a new ProtoStrap.
        using var repo = new FixtureRepo();
        var builder = TwoProjects(repo);

        var problems = await TestApp.ProblemsAsync(builder, new MSBuildSourceTracer(repo.Root));

        Assert.Equal(
        [
            "api: no global.json at or above services/api pins the .NET SDK it builds with: add one that sets sdk.version",
            "worker: no global.json at or above services/worker pins the .NET SDK it builds with: add one that sets sdk.version",
        ], problems);
    }

    [Fact]
    public async Task AGlobalJsonMustPinTheSdk()
    {
        using var repo = new FixtureRepo();
        repo.Write("global.json", """{ "test": { "runner": "Microsoft.Testing.Platform" } }""");
        var builder = TwoProjects(repo);

        var problems = await TestApp.ProblemsAsync(builder, new MSBuildSourceTracer(repo.Root));

        Assert.Equal(
        [
            "api: global.json doesn't pin the .NET SDK it builds with: set sdk.version",
            "worker: global.json doesn't pin the .NET SDK it builds with: set sdk.version",
        ], problems);
    }

    [Fact]
    public async Task AGlobalJsonInTheProjectsDirectoryPinsIt()
    {
        using var repo = new FixtureRepo();
        repo.Write("services/api/global.json", """{ "sdk": { "version": "10.0.100", "rollForward": "latestFeature" } }""");
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddProject("api", repo.Project("services/api/Api.csproj", "Microsoft.NET.Sdk.Web"))
            .PublishAsProtoStrapService(s => s.Request(cpu: "500m", memory: "512Mi").Ready(Aspire.Hosting.Readiness.Grpc));

        var result = await TestApp.GenerateAsync(builder, new MSBuildSourceTracer(repo.Root));

        Assert.Empty(result.Problems);
    }

    [Fact]
    public async Task ADockerfileNeedsNoGlobalJson()
    {
        using var repo = new FixtureRepo();
        repo.Write("services/web/Dockerfile", "FROM node:22\n");
        var builder = TestApp.Publish(repo);
        builder.AddEnvironment();
        builder.AddDockerfile("web", repo.PathOf("services/web"))
            .WithHttpEndpoint(targetPort: 3000)
            .PublishAsProtoStrapService(s => s.Request(cpu: "250m", memory: "256Mi").Ready("/healthz"));

        var result = await TestApp.GenerateAsync(builder, new MSBuildSourceTracer(repo.Root));

        Assert.Empty(result.Problems);
        Assert.DoesNotContain(result.Warnings, w => w.Contains("global.json", StringComparison.Ordinal));
    }
}

internal static class KeycloakLike
{
    /// <summary>
    /// AddKeycloakLike adds a service that runs an upstream image, the way Aspire's Keycloak
    /// integration does.
    /// </summary>
    public static IResourceBuilder<ContainerResource> AddKeycloakLike(this IDistributedApplicationBuilder builder, string name) =>
        builder.AddContainer(name, "quay.io/keycloak/keycloak", "26.7")
            .WithHttpEndpoint(targetPort: 8080)
            .WithArgs("start");
}
