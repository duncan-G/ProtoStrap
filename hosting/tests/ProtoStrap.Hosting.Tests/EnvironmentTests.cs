    [Fact]
    public async Task TheEnvironmentsSettingsAreTheTopOfTheSpec()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddProtoStrapEnvironment("protostrap", app: "protofast")
            .WithVersion("1.4.0")
            .WithIngressPool(vm: "c8g.medium")
            .WithGeneralPool(vm: ["m7g.large", "m6g.large", "m8g.large", "m7gd.large"], min: 1, max: 6, spare: 1, target: 0.70)
            .WithComputePool(vm: ["c7g.xlarge", "c6g.xlarge", "c8g.xlarge", "c7gd.xlarge"], min: 0, max: 4)
            .WithDataPool(vm: "m7g.xlarge", count: 1);
        AddApi(builder, repo);

        var yaml = await TestApp.GenerateYamlAsync(builder);

        Assert.StartsWith("""
            # Generated by ProtoStrap.Hosting 0.1.3 from apphost/Test.AppHost.csproj.
            # Do not edit: change the AppHost, then run `aspire do protostrap-spec`.
            app: protofast
