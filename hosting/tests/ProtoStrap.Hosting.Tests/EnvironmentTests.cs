            pools:
              ingress: { vm: c8g.medium }
              general:
                vm: [m7g.large, m6g.large, m8g.large, m7gd.large]
                min: 1
                max: 6
                spare: 1
                target: 70%
                reserved: { cpu: 400m, memory: 1Gi }
              compute:
                vm: [c7g.xlarge, c6g.xlarge, c8g.xlarge, c7gd.xlarge]
                min: 0
                max: 4
                spare: 0
                target: 85%
                reserved: { cpu: 400m, memory: 1Gi }
              data: { vm: m7g.xlarge, count: 1 }

            components:
              api:

            """, yaml);
    }

