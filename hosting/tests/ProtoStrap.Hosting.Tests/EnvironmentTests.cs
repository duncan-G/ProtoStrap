    [Fact]
    public async Task MissingAndInvalidSettingsAreAllReported()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);
        builder.AddProtoStrapEnvironment("protostrap", app: "ProtoFast")
            .WithVersion("next")
            .AddEnvoyGateway("gateway")
            .WithHost("app", "protofast.dev", local: "app.localhost")
            .WithHost("Web Site", "not a host", local: "web.localhost")
            .WithHost("other", "protofast.dev", local: "other.localhost")
            .WithRequest(cpu: "half", memory: "256MB");
        AddApi(builder, repo);

        var problems = await TestApp.ProblemsAsync(builder);

        Assert.Equal(
        [
            "protostrap: app \"ProtoFast\" must be up to 30 lowercase letters, digits and dashes",
            "protostrap: WithVersion(\"next\") isn't a ProtoStrap version, like 1.4.0",
            "protostrap: no ingress pool: call WithIngressPool(vm: ...)",
            "protostrap: no general pool: call WithGeneralPool(vm: [...], min: ..., max: ...)",
            "protostrap: no data pool: call WithDataPool(vm: ...)",
            "gateway: WithRequest: cpu \"half\" isn't CPU, like \"500m\" or \"2\"",
            "gateway: WithRequest: memory \"256MB\" isn't memory, like \"512Mi\" or \"1Gi\"",
            "gateway: WithHost: \"Web Site\" isn't a host's name: lowercase letters, digits and dashes",
            "gateway: WithHost: \"not a host\" isn't a host name",
            "gateway: WithHost: other has protofast.dev too, which app has: each host has a hostname of its own",
        ], problems);
    }

