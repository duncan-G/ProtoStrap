    }

    private static async Task<Dictionary<string, object>> RunModeEnvironmentAsync(IResource resource)
    {
        var values = new Dictionary<string, object>();
        var context = new EnvironmentCallbackContext(new DistributedApplicationExecutionContext(DistributedApplicationOperation.Run), resource, values);
        foreach (var callback in resource.Annotations.OfType<EnvironmentCallbackAnnotation>())
            await callback.Callback(context);
        return values;
    }

    [Fact]
    public async Task PublishModeAddsTheProtoStrapSpecStepBeforePublish()
    {
        using var repo = new FixtureRepo();
        var builder = TestApp.Publish(repo);

        var protostrap = builder.AddEnvironment();

        Assert.Contains(protostrap.Resource, builder.Resources);
        Assert.True(protostrap.Resource.IsExcludedFromPublish());
        var annotation = Assert.Single(protostrap.Resource.Annotations.OfType<PipelineStepAnnotation>());
        var steps = (await annotation.CreateStepsAsync(new PipelineStepFactoryContext
        {
            PipelineContext = null!,
            Resource = protostrap.Resource,
        })).ToList();
        var step = Assert.Single(steps);
        Assert.Equal("protostrap-spec", step.Name);
        Assert.Contains(WellKnownPipelineSteps.Publish, step.RequiredBySteps);
        Assert.Empty(step.DependsOnSteps);
    }

