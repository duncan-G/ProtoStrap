    private string AppHostProject(string? gitRoot)
    {
        var directory = environment.AppHostDirectory;
        var projects = Directory.Exists(directory) ? Directory.GetFiles(directory, "*.csproj") : [];
        var path = projects.Length == 1 ? projects[0] : directory;
        var from = gitRoot ?? _root;
        return PathUtil.IsInside(path, from) ? PathUtil.Relative(from, path) : Path.GetFileName(path);
    }

    private static string? FindGitRoot(string directory)
    {
        for (var d = Path.GetFullPath(directory); d is not null; d = Path.GetDirectoryName(d))
        {
            var git = Path.Combine(d, ".git");
            if (Directory.Exists(git) || File.Exists(git))
                return d;
        }
        return null;
    }

    /// <summary>
    /// ReadyField writes a readiness check, as protostrap check would accept it
    /// (docs/protostrap.md#readiness-checks), or reports why it can't work.
    /// </summary>
    private YamlNode? ReadyField(Component c, ComponentKind kind, Readiness ready, ComponentSettings settings)
    {
        var routed = kind == ComponentKind.Service && settings.Routes.Count > 0;
        if (ready.CommandLine is { } command)
        {
            if (command.Count == 0 || command.Any(string.IsNullOrWhiteSpace))
                Problem(c, "Ready: a command can't be empty");
            else if (routed)
                Problem(c, "Ready: the edge checks a routed service too, and can't run a command: use Readiness.Grpc, Readiness.Tcp or an HTTP path");
            else
                return Seq(command);
            return null;
        }
        if (ready.Kind == "http" && ready.Path?.StartsWith('/') != true)
        {
            Problem(c, $"Ready: \"{ready.Path}\" must be Readiness.Grpc, Readiness.Tcp or an HTTP path such as \"/healthz\"");
            return null;
        }
        if (ready.Port is null && c.Port is null)
        {
            var example = ready.Kind switch
            {
                "grpc" => "Readiness.Grpc.On(8081)",
                "tcp" => "Readiness.Tcp.On(8081)",
                _ => $"Readiness.Http(\"{ready.Path}\").On(8081)",
            };
            Problem(c, $"Ready: a {kind.ToString().ToLowerInvariant()} has no port, so its check names one, such as {example}");
            return null;
        }
        var protocol = settings.Protocol ?? (ready.Kind == "grpc" && ready.Port is null ? GatewayProtocol.Grpc : GatewayProtocol.Http1);
        if (routed && ready.Kind == "grpc" && protocol == GatewayProtocol.Http1)
        {
            Problem(c, "Ready: the edge checks gRPC over its HTTP/2 connections to the service: set Protocol(GatewayProtocol.Http2) or Protocol(GatewayProtocol.Grpc)");
            return null;
        }
        return YamlScalar.String(ready.Value!);
    }

    /// <summary>
    /// InferredReadiness is the path of a readiness probe, otherwise of WithHttpHealthCheck, on the
    /// port of the endpoint it checks when that isn't the component's own.
    /// </summary>
    private static Readiness? InferredReadiness(Component c, IResource resource)
    {
        var endpoints = resource.Annotations.OfType<EndpointAnnotation>().ToList();
        Readiness OnEndpoint(string path, string? endpoint) =>
            endpoints.FirstOrDefault(e => e.Name == endpoint)?.TargetPort is { } port && port != c.Port
                ? Readiness.Http(path).On(port)
                : Readiness.Http(path);

        if (resource.Annotations.OfType<EndpointProbeAnnotation>().FirstOrDefault(p => p.Type == ProbeType.Readiness) is { } probe)
            return OnEndpoint(probe.Path, probe.EndpointReference?.EndpointName);

        // WithHttpHealthCheck keeps its endpoint and path only in the check's key:
        // <resource>_<endpoint>_<path>_<status>_check.
        var pattern = new Regex("^" + Regex.Escape(resource.Name) + "_(?<endpoint>[^/]+?)_(?<path>/.*)_(?<status>[0-9]{3})_check$");
        var check = resource.Annotations.OfType<HealthCheckAnnotation>()
            .Select(h => pattern.Match(h.Key))
            .FirstOrDefault(m => m.Success);
        return check is null ? null : OnEndpoint(check.Groups["path"].Value, check.Groups["endpoint"].Value);
    }

    /// <summary>
    /// ImageName writes an image as Docker would pull it, with Docker Hub's images, official or
    /// not, by their short names.
    /// </summary>
    private static string ImageName(ContainerImageAnnotation image)
    {
        var name = (string.IsNullOrEmpty(image.Registry) ? "" : image.Registry + "/") + image.Image;
        foreach (var prefix in new[] { "docker.io/library/", "index.docker.io/library/", "docker.io/", "index.docker.io/", "library/" })
        {
            if (name.StartsWith(prefix, StringComparison.Ordinal))
            {
                name = name[prefix.Length..];
                break;
            }
        }
        return string.IsNullOrEmpty(image.SHA256)
            ? $"{name}:{(string.IsNullOrEmpty(image.Tag) ? "latest" : image.Tag)}"
            : $"{name}@sha256:{image.SHA256}";
    }

    /// <summary>
    /// InsideRepository says whether a declared source, a path or a git pathspec, stays inside the
    /// repository.
    /// </summary>
    private static bool InsideRepository(string source)
    {
        var path = source;
        if (path.StartsWith(":(", StringComparison.Ordinal) && path.IndexOf(')') is var end and > 0)
            path = path[(end + 1)..];
        else if (path.Length > 1 && path[0] == ':' && "!^".Contains(path[1]))
            path = path[2..];
        path = path.Replace('\\', '/');
        return path.Length > 0 && !path.StartsWith('/') && !Path.IsPathRooted(path)
            && path != ".." && !path.StartsWith("../", StringComparison.Ordinal);
    }

    private static bool SetByProtoStrap(string key) =>
        key.StartsWith("PROTOSTRAP_", StringComparison.Ordinal)
        || key.StartsWith("AWS_", StringComparison.Ordinal)
        || key is "SECRET_ID" or "SECRET_PREFIX" or "FILES_BUCKET" or "BACKUPS_BUCKET"
        || key.StartsWith("BUCKET_", StringComparison.Ordinal)
        || (key.StartsWith("QUEUE_", StringComparison.Ordinal) && key.EndsWith("_URL", StringComparison.Ordinal));

    private static YamlSeq Seq(IEnumerable<string> items, YamlStyle style = YamlStyle.Auto) =>
        new(style, items.Select(i => (YamlNode)i));

    private static string Number(double value) => value.ToString(CultureInfo.InvariantCulture);

    private static string And(IEnumerable<string> items)
    {
        var list = items.ToList();
        return list.Count <= 1 ? string.Concat(list) : string.Join(", ", list[..^1]) + " and " + list[^1];
    }

