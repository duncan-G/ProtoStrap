using System.Globalization;
using System.Reflection;
using System.Text.RegularExpressions;
using Aspire.Hosting;
using Aspire.Hosting.ApplicationModel;
using ProtoStrap.Hosting.Sources;
using ProtoStrap.Hosting.Yaml;

namespace ProtoStrap.Hosting.Spec;

/// <summary>SpecResult is the spec, or why there isn't one.</summary>
/// <param name="SpecPath">It is where protostrap.yaml goes.</param>
/// <param name="Yaml">It is the spec, or null if there are problems.</param>
/// <param name="Problems">They stop the spec being written, and each starts with the resource at fault.</param>
/// <param name="Warnings">They say what is left out of the spec, or left floating, and why.</param>
internal sealed record SpecResult(string SpecPath, string? Yaml, IReadOnlyList<string> Problems, IReadOnlyList<string> Warnings);

/// <summary>
/// SpecGenerator turns the app model, built in publish mode, into protostrap.yaml
/// (docs/protostrap-aspire.md, "The generator"): it collects the compute resources deployed to
/// the environment, resolves their environment and arguments, traces each built component's
/// sources, and writes the spec in a fixed order, with repository-relative paths and nothing
/// that varies between runs. Every problem is collected, so one run lists them all.
/// </summary>
internal sealed partial class SpecGenerator(
    DistributedApplicationModel model,
    DistributedApplicationExecutionContext execution,
    ProtoStrapEnvironmentResource environment,
    Func<string, ISourceTracer> tracerFactory)
{
    private static readonly string[] FieldOrder =
    [
        "kind", "project", "build", "context", "sources", "image", "command", "pool", "vm", "request", "port", "protocol", "ready",
        "routes", "authorize", "metrics", "depends_on", "uses", "migrate", "configure", "env", "secrets", "secret_prefix", "secret_files",
        "on_secret_change", "config", "on_config_change", "stop", "volume", "backup", "scale",
    ];

    private static readonly HashSet<string> ReservedNames = ["edge", "telemetry", "protostrap", "scheduler", "agent"];

    private readonly List<string> _problems = [];
    private readonly List<string> _warnings = [];
    private readonly Dictionary<IResource, Component> _components = [];
    private readonly Dictionary<IResource, Task<ProjectSources>> _traces = [];
    private readonly Dictionary<IResource, Component> _configuredBy = [];
    private string _root = "";
    private ISourceTracer _tracer = null!;

    /// <summary>
    /// PackageVersion is ProtoStrap.Hosting's version, which is also the ProtoStrap version a spec
    /// runs by default.
    /// </summary>
    public static string PackageVersion { get; } =
        typeof(SpecGenerator).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion.Split('+')[0] ?? "0.0.0";

    public async Task<SpecResult> GenerateAsync(CancellationToken cancellationToken)
    {
        var gitRoot = FindGitRoot(environment.AppHostDirectory);
        string specPath;
        if (environment.SpecPath is { } given)
        {
            specPath = Path.GetFullPath(Path.Combine(environment.AppHostDirectory, given));
        }
        else if (gitRoot is not null)
        {
            specPath = Path.Combine(gitRoot, "protostrap.yaml");
        }
        else
        {
            _problems.Add($"{environment.Name}: {environment.AppHostDirectory} isn't in a git repository: call WithSpecPath(...) to say where protostrap.yaml goes");
            return new SpecResult(Path.Combine(environment.AppHostDirectory, "protostrap.yaml"), null, _problems, _warnings);
        }
        _root = Path.GetDirectoryName(specPath)!;
        _tracer = tracerFactory(_root);

        var document = new YamlMap(YamlStyle.Block);
        Top(document);
        document.AddGroupBreak();
        document["pools"] = Pools();
        document.AddGroupBreak();
        document["edge"] = Edge();
        if (Queues() is { Count: > 0 } queues)
        {
            document.AddGroupBreak();
            document["queues"] = queues;
        }
        if (Buckets() is { Count: > 0 } buckets)
        {
            document.AddGroupBreak();
            document["buckets"] = buckets;
        }
        if (Email() is { } email)
        {
            document.AddGroupBreak();
            document["email"] = email;
        }
        document.AddGroupBreak();
        document["components"] = await ComponentsAsync(cancellationToken);

        if (_problems.Count > 0)
            return new SpecResult(specPath, null, _problems, _warnings);
        var header = new[]
        {
            $"Generated by ProtoStrap.Hosting {PackageVersion} from {AppHostProject(gitRoot)}.",
            "Do not edit: change the AppHost, then run `aspire do protostrap-spec`.",
        };
        return new SpecResult(specPath, YamlWriter.Write(document, header), _problems, _warnings);
    }

    // This section writes the environment's keys: app, protostrap, hosts, pools and edge.

    private void Top(YamlMap document)
    {
        var at = environment.Name + ": ";
        if (!DnsLabel().IsMatch(environment.App) || environment.App.Length > 30)
            _problems.Add($"{at}app \"{environment.App}\" must be up to 30 lowercase letters, digits and dashes");
        var version = environment.Version ?? PackageVersion;
        if (!SemVer().IsMatch(version))
            _problems.Add($"{at}WithVersion(\"{version}\") isn't a ProtoStrap version, like 1.4.0");
        document["app"] = environment.App;
        document["protostrap"] = version;

        var named = new Dictionary<string, string>(StringComparer.Ordinal); // It maps each hostname to the first host's name.
        foreach (var host in environment.HostSettings)
        {
            if (!DnsLabel().IsMatch(host.Name))
                _problems.Add($"{at}WithHost: \"{host.Name}\" isn't a host's name: lowercase letters, digits and dashes");
            if (!HostName().IsMatch(host.Hostname))
                _problems.Add($"{at}WithHost: \"{host.Hostname}\" isn't a host name");
            else if (named.TryGetValue(host.Hostname, out var other) && other != host.Name)
                _problems.Add($"{at}WithHost: {host.Name} has {host.Hostname} too, which {other} has: each host has a hostname of its own");
            else
                named.TryAdd(host.Hostname, host.Name);
        }
        if (environment.Hosts.Count > 0)
        {
            var hosts = new YamlMap(YamlStyle.Block);
            foreach (var (name, hostname) in environment.Hosts.OrderBy(h => h.Key, StringComparer.Ordinal))
                hosts[name] = hostname;
            document["hosts"] = hosts;
        }
    }

    private YamlMap Pools()
    {
        var at = environment.Name + ": ";
        var pools = new YamlMap(YamlStyle.Block);

        if (environment.IngressPool is not { } ingress)
        {
            _problems.Add(at + "no ingress pool: call WithIngressPool(vm: ...)");
        }
        else
        {
            var map = new YamlMap { ["vm"] = ingress.Vm };
            if (ingress.ReservedCpu is not null || ingress.ReservedMemory is not null)
                map["reserved"] = Reserved("WithIngressPool", ingress.ReservedCpu ?? "200m", ingress.ReservedMemory ?? "512Mi");
            pools["ingress"] = map;
        }

        if (environment.GeneralPool is not { } general)
            _problems.Add(at + "no general pool: call WithGeneralPool(vm: [...], min: ..., max: ...)");
        else
            pools["general"] = ScalingPool("WithGeneralPool", general, minMin: 1, spare: 1, target: 0.70);

        if (environment.ComputePool is { } compute)
            pools["compute"] = ScalingPool("WithComputePool", compute, minMin: 0, spare: 0, target: 0.85);

        if (environment.DataPool is not { } data)
        {
            _problems.Add(at + "no data pool: call WithDataPool(vm: ...)");
        }
        else
        {
            if (data.Count is < 1 or > 3)
                _problems.Add($"{at}WithDataPool: count {data.Count} must be 1 to 3");
            var map = new YamlMap { ["vm"] = data.Vm, ["count"] = YamlScalar.Number(data.Count) };
            if (data.ReservedCpu is not null || data.ReservedMemory is not null)
                map["reserved"] = Reserved("WithDataPool", data.ReservedCpu ?? "0", data.ReservedMemory ?? "1Gi");
            pools["data"] = map;
        }
        return pools;
    }

    private YamlMap ScalingPool(string method, ScalingPoolSettings pool, int minMin, int spare, double target)
    {
        var at = $"{environment.Name}: {method}: ";
        if (pool.Vm.Count == 0)
            _problems.Add(at + "vm needs one or more instance types of one shape");
        if (pool.Min < 0)
            _problems.Add($"{at}min {pool.Min} is negative");
        else if (pool.Min < minMin)
            _problems.Add($"{at}min {pool.Min} must be at least {minMin}");
        if (pool.Max < 1)
            _problems.Add($"{at}max {pool.Max} must be at least 1");
        else if (pool.Max < pool.Min)
            _problems.Add($"{at}max {pool.Max} is below min {pool.Min}");
        if (pool.Spare < 0)
            _problems.Add($"{at}spare {pool.Spare} is negative");
        var percent = Quantity.Percent(pool.Target ?? target);
        if (percent is null)
            _problems.Add($"{at}target {Number(pool.Target ?? target)} must be above 0 and at most 1, such as 0.70");

        return new YamlMap(YamlStyle.Block)
        {
            ["vm"] = Seq(pool.Vm),
            ["min"] = YamlScalar.Number(pool.Min),
            ["max"] = YamlScalar.Number(pool.Max),
            ["spare"] = YamlScalar.Number(pool.Spare ?? spare),
            ["target"] = percent ?? "",
            ["reserved"] = Reserved(method, pool.ReservedCpu ?? "400m", pool.ReservedMemory ?? "1Gi"),
        };
    }

    private YamlMap Reserved(string method, string cpu, string memory)
    {
        var at = $"{environment.Name}: {method}: ";
        var cpuValue = Quantity.Cpu(cpu);
        if (cpuValue is null)
            _problems.Add($"{at}reserved cpu \"{cpu}\" isn't CPU, like \"500m\" or \"2\"");
        var memoryValue = Quantity.Memory(memory);
        if (memoryValue is null)
            _problems.Add($"{at}reserved memory \"{memory}\" isn't memory, like \"512Mi\" or \"1Gi\"");
        return new YamlMap { ["cpu"] = cpuValue ?? cpu, ["memory"] = memoryValue ?? memory };
    }

    private YamlMap Edge()
    {
        var at = $"{environment.Name}: WithEdge: ";
        var edge = environment.Edge ?? new ResourceSettings("500m", "256Mi");
        var cpu = Quantity.Cpu(edge.Cpu);
        if (cpu is null)
            _problems.Add($"{at}cpu \"{edge.Cpu}\" isn't CPU, like \"500m\" or \"2\"");
        else if (cpu == "0m")
            _problems.Add(at + "cpu must be above 0");
        var memory = Quantity.Memory(edge.Memory);
        if (memory is null)
            _problems.Add($"{at}memory \"{edge.Memory}\" isn't memory, like \"512Mi\" or \"1Gi\"");
        else if (memory == "0Mi")
            _problems.Add(at + "memory must be above 0");
        return new YamlMap(YamlStyle.Block)
        {
            ["request"] = new YamlMap { ["cpu"] = cpu ?? edge.Cpu, ["memory"] = memory ?? edge.Memory },
        };
    }

    // This section writes the queues.

    private YamlMap Queues()
    {
        var queues = new YamlMap(YamlStyle.Block);
        foreach (var queue in model.Resources.OfType<ProtoStrapQueueResource>()
            .Where(q => !q.IsExcludedFromPublish())
            .OrderBy(q => q.Name, StringComparer.Ordinal))
        {
            var at = queue.Name + ": ";
            if (!DnsLabel().IsMatch(queue.Name))
                _problems.Add(at + "a queue's name is lowercase letters, digits and dashes");
            else if (queue.Name.Length > 70)
                _problems.Add(at + "a queue's name is at most 70 characters");
            else if (queue.Name is "files" or "backups")
                _problems.Add(at + "a queue can't be called files or backups, which name ProtoStrap's buckets in uses");
            var settings = new YamlMap();
            if (queue.Fifo)
                settings["fifo"] = YamlScalar.Bool(true);
            if (queue.Visibility is { } visibility)
            {
                if (visibility < TimeSpan.FromSeconds(1) || visibility > TimeSpan.FromHours(12))
                    _problems.Add(at + "visibility must be between 1s and 12h");
                settings["visibility"] = Quantity.Duration(visibility) ?? "";
            }
            if (queue.Retention is { } retention)
            {
                if (retention < TimeSpan.FromMinutes(1) || retention > TimeSpan.FromDays(14))
                    _problems.Add(at + "retention must be between 1m and 14d");
                settings["retention"] = Quantity.Duration(retention) ?? "";
            }
            if (queue.MaxReceives is { } maxReceives)
            {
                if (maxReceives is < 1 or > 1000)
                    _problems.Add(at + "maxReceives must be 1 to 1000");
                settings["max_receives"] = YamlScalar.Number(maxReceives);
            }
            queues[queue.Name] = settings;
        }
        return queues;
    }

    // This section writes the application's own buckets, with the rules `protostrap check`
    // applies (internal/spec/check.go). Aspire refuses a name with -- and two resources of one
    // name, so a bucket never meets the first rule or shares a queue's name.

    private YamlMap Buckets()
    {
        var buckets = new YamlMap(YamlStyle.Block);
        foreach (var bucket in model.Resources.OfType<ProtoStrapBucketResource>()
            .Where(b => !b.IsExcludedFromPublish())
            .OrderBy(b => b.Name, StringComparer.Ordinal))
        {
            var at = bucket.Name + ": ";
            if (!DnsLabel().IsMatch(bucket.Name))
                _problems.Add(at + "a bucket's name is lowercase letters, digits and dashes");
            else if (bucket.Name.Length > 24)
                _problems.Add(at + "a bucket's name is at most 24 characters");
            else if (bucket.Name.EndsWith("-s3alias", StringComparison.Ordinal))
                _problems.Add(at + "S3 refuses a bucket name ending in -s3alias");
            else if (bucket.Name is "files" or "backups" or "deploy" or "tfstate" or "telemetry")
                _problems.Add(at + "files, backups, deploy, tfstate and telemetry are ProtoStrap's own buckets");
            var settings = new YamlMap();
            if (bucket.Browser)
                settings["browser"] = YamlScalar.Bool(true);
            if (bucket.Versions is { } versions)
                settings["versions"] = Days(versions, at + "versions");
            if (bucket.Locked)
            {
                if (bucket.Versions is null)
                    _problems.Add(at + "locked needs versions: S3 locks only a versioned bucket");
                settings["lock"] = YamlScalar.Bool(true);
            }
            if (bucket.Expire is { } expire)
                settings["expire"] = Days(expire, at + "expire");
            buckets[bucket.Name] = settings;
        }
        return buckets;
    }

    // This section writes the domains the application sends mail from, with the rules
    // `protostrap check` applies (internal/spec/email.go). An application has one email.

    private YamlMap? Email()
    {
        var all = model.Resources.OfType<ProtoStrapEmailResource>().Where(e => !e.IsExcludedFromPublish()).ToList();
        if (all.Count == 0)
            return null;
        foreach (var extra in all.Skip(1))
            _problems.Add($"{extra.Name}: the application already has email: list every domain in one AddProtoStrapEmail");
        var email = all[0];
        var at = email.Name + ": ";
        if (email.Domains.Count == 0)
            _problems.Add(at + "list at least one domain to send mail from");
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var domain in email.Domains)
        {
            if (domain.StartsWith("*.", StringComparison.Ordinal) || !HostName().IsMatch(domain))
                _problems.Add($"{at}\"{domain}\" isn't a domain to send mail from, such as example.com");
            else if (!seen.Add(domain))
                _problems.Add($"{at}{domain} is listed twice");
        }
        return new YamlMap(YamlStyle.Block) { ["domains"] = Seq(email.Domains.Distinct().Order(StringComparer.Ordinal)) };
    }

    // Days writes a bucket's duration, which S3's lifecycle rules count in whole days.
    private string Days(TimeSpan duration, string what)
    {
        if (duration < TimeSpan.FromDays(1) || duration.Ticks % TimeSpan.TicksPerDay != 0)
        {
            _problems.Add(what + " must be a whole number of days, at least 1 day");
            return "";
        }
        return Quantity.Duration(duration) ?? "";
    }

    // This section writes the components.

    private async Task<YamlMap> ComponentsAsync(CancellationToken cancellationToken)
    {
        var resources = model.Resources
            .Where(r => r is IComputeResource && !r.IsExcludedFromPublish())
            .Where(r => r.GetComputeEnvironment() is null || r.GetComputeEnvironment() == environment)
            .OrderBy(r => r.Name, StringComparer.Ordinal)
            .ToList();

        // The first pass works out what every component is and the port it serves on, which
        // references to it need.
        foreach (var resource in resources)
            _components[resource] = Identify(resource);

        // A configure task belongs to the first component that names it, in the order the
        // AppHost added them, so a second one is the one at fault.
        foreach (var resource in model.Resources.Where(_components.ContainsKey))
        {
            foreach (var configure in resource.Annotations.OfType<ProtoStrapConfigureAnnotation>())
                _configuredBy.TryAdd(configure.Task, _components[resource]);
        }

        // Every project's sources are traced at once: MSBuild evaluates a project shared by
        // several components once, and the rest side by side.
        foreach (var (resource, component) in _components)
        {
            if (resource is ProjectResource project && component.Settings is { Kind: not ComponentKind.Stateful }
                && !resource.HasAnnotationOfType<DockerfileBuildAnnotation>()
                && Path.GetFullPath(project.GetProjectMetadata().ProjectPath) is var path && PathUtil.IsInside(path, _root))
            {
                _traces[resource] = _tracer.TraceAsync(path, cancellationToken);
            }
        }

        var components = new YamlMap(YamlStyle.Block) { BlankLineBetweenEntries = true };
        foreach (var resource in resources)
        {
            if (await ComponentAsync(_components[resource], cancellationToken) is { } entry)
                components[resource.Name] = entry;
        }

        var projects = _components.Values.Where(c => c.Traced is not null).ToList();
        foreach (var project in projects.Where(c => c.Traced!.ContainerBaseImage?.Contains("@sha256:", StringComparison.Ordinal) != true))
            _warnings.Add($"{project.Name}: ContainerBaseImage isn't pinned by digest, so a patched base image changes nothing in the repository");
        return components;
    }

    private static Component Identify(IResource resource)
    {
        var component = new Component(resource);
        if (!resource.TryGetLastAnnotation<ProtoStrapComponentAnnotation>(out var annotation))
            return component;
        component.Method = annotation.Method;
        try
        {
            component.Settings = annotation.Configure();
        }
        catch (Exception e)
        {
            component.CallbackError = e;
            return component;
        }

        var kind = component.Settings.Kind;
        var endpoints = resource.Annotations.OfType<EndpointAnnotation>().ToList();
        component.Primary = kind switch
        {
            ComponentKind.Service => endpoints.FirstOrDefault(e => e.Name == "http")
                ?? endpoints.FirstOrDefault(e => e.UriScheme == "http")
                ?? endpoints.FirstOrDefault(e => e.UriScheme != "https")
                ?? endpoints.FirstOrDefault(),
            ComponentKind.Stateful => endpoints.FirstOrDefault(e => e.Name == "tcp") ?? endpoints.FirstOrDefault(),
            _ => null,
        };
        component.Port = component.Primary?.TargetPort;
        // A project listens on 8080 in its container, the .NET SDK's default.
        if (component.Port is null && kind == ComponentKind.Service && resource is ProjectResource && component.Primary?.UriScheme is null or "http")
            component.Port = 8080;
        return component;
    }

    private async Task<YamlMap?> ComponentAsync(Component c, CancellationToken cancellationToken)
    {
        var resource = c.Resource;
        if (resource is ExecutableResource)
        {
            Problem(c, "AddExecutable runs a process on the AppHost's machine: exclude it from publish with ExcludeFromManifest(), or don't add it in publish mode");
            return null;
        }

        if (!DnsLabel().IsMatch(c.Name))
            Problem(c, "a component's name is lowercase letters, digits and dashes");
        else if (c.Name.Length > 40)
            Problem(c, "a component's name is at most 40 characters");
        else if (ReservedNames.Contains(c.Name))
            Problem(c, $"\"{c.Name}\" is reserved for ProtoStrap");

        if (c.Settings is not { } settings)
        {
            Problem(c, c.CallbackError is { } error
                ? $"{c.Method} failed: {error.Message}"
                : "no PublishAsProtoStrap* call: say whether it is a service, worker, stateful component or task");
            return null;
        }

        var kind = settings.Kind;
        var built = kind != ComponentKind.Stateful;
        var fields = new Dictionary<string, YamlNode>(StringComparer.Ordinal) { ["kind"] = kind.ToString().ToLowerInvariant() };

        // These fields say what the component runs.
        if (built ? !await BuildAsync(c, fields, cancellationToken) : !Image(c, fields))
            return null;

        // These checks reject what ProtoStrap can't do for the component.
        foreach (var mount in resource.Annotations.OfType<ContainerMountAnnotation>().Where(m => m.Type == ContainerMountType.BindMount))
            Problem(c, $"bind mount at {mount.Target}: a replica can't mount the repository, so copy the files into the image, or make them config files with WithProtoStrapConfig");
        if (resource.HasAnnotationOfType<ContainerRuntimeArgsCallbackAnnotation>())
            Problem(c, "WithContainerRuntimeArgs isn't supported: ProtoStrap's agent starts every container the same way");
        if (resource.TryGetLastAnnotation<ReplicaAnnotation>(out var replicas))
            Problem(c, $"WithReplicas({replicas.Replicas}) isn't supported: Scale(min: ..., max: ...) sets how many replicas run");
        if (resource is ContainerResource { Entrypoint.Length: > 0 } && resource is not RedisResource)
            Problem(c, "WithEntrypoint isn't supported: a component's image runs with its own entrypoint");
        if (built)
        {
            foreach (var mount in resource.Annotations.OfType<ContainerMountAnnotation>().Where(m => m.Type == ContainerMountType.Volume))
                Problem(c, $"a volume at {mount.Target}: only a stateful component keeps data, so replicas can come and go");
        }

        // These fields say where the component runs, and what it reserves.
        if (built)
        {
            var pool = settings.Pool ?? Pool.General;
            if (pool == Pool.Compute && environment.ComputePool is null)
                Problem(c, "Pool: the environment has no compute pool: call WithComputePool(...)");
            fields["pool"] = pool.ToString().ToLowerInvariant();
        }
        else if (settings.Vm is not { } vm)
        {
            Problem(c, "no data VM: call Vm(\"data-1\")");
        }
        else
        {
            var count = environment.DataPool?.Count ?? 1;
            if (DataVm().Match(vm) is not { Success: true } match || int.Parse(match.Groups[1].Value, CultureInfo.InvariantCulture) > count)
                Problem(c, $"Vm: there is no {vm}: the data pool has data-1 to data-{count}");
            fields["vm"] = vm;
        }
        if (Request(c, settings.Request) is { } request)
            fields["request"] = request;

        // These fields say how the component is reached.
        if (kind is ComponentKind.Service or ComponentKind.Stateful)
        {
            if (c.Port is { } port)
            {
                fields["port"] = YamlScalar.Number(port);
            }
            else
            {
                Problem(c, kind == ComponentKind.Stateful
                    ? "no port: give it an endpoint with a target port, such as WithEndpoint(targetPort: 9000, name: \"tcp\")"
                    : "no port: give it an http endpoint with a target port, such as WithHttpEndpoint(targetPort: 8080)");
            }
        }
        if (kind is ComponentKind.Service or ComponentKind.Worker or ComponentKind.Stateful)
        {
            var ready = settings.Ready ?? InferredReadiness(c, resource);
            if (ready is not null && ReadyField(c, kind, ready, settings) is { } field)
                fields["ready"] = field;
            else if (ready is null && kind == ComponentKind.Service)
                Problem(c, "no readiness check: call Ready(Readiness.Grpc) or Ready(\"/healthz\"), or WithHttpHealthCheck(\"/healthz\")");
        }
        if (kind == ComponentKind.Service)
        {
            if (settings.Protocol is { } protocol)
                fields["protocol"] = YamlScalar.String(protocol.ToString().ToLowerInvariant());
            if (Routes(c, settings.Routes) is { } routes)
                fields["routes"] = routes;
            if (settings.Authorize is { } authorize && Authorize(c, settings, authorize) is { } authorizeMap)
                fields["authorize"] = authorizeMap;
        }
        if (settings.Metrics is { } metrics)
        {
            if (metrics.Port is < 1 or > 65535)
                Problem(c, $"Metrics: port {metrics.Port} must be 1 to 65535");
            else if (!metrics.Path.StartsWith('/'))
                Problem(c, $"Metrics: path \"{metrics.Path}\" must start with /");
            else
                fields["metrics"] = metrics.Port.ToString(CultureInfo.InvariantCulture) + metrics.Path;
        }

        // These fields say what the component needs, and how it starts and stops.
        Waits(c, kind, fields);
        var signals = settings.Scale?.Demand.OfType<QueueSignal>().Select(q => q.Queue.Name).ToHashSet(StringComparer.Ordinal) ?? [];
        var uses = resource.Annotations.OfType<ProtoStrapUsesAnnotation>()
            .Select(u => u.Target)
            .Where(t => !t.IsExcludedFromPublish())
            .Select(t => t switch
            {
                ProtoStrapFilesResource => "files",
                ProtoStrapEmailResource => "email",
                _ => t.Name,
            })
            .Where(name => !signals.Contains(name))
            .Distinct()
            .Order(StringComparer.Ordinal)
            .ToList();
        if (uses.Count > 0)
            fields["uses"] = Seq(uses);
        await EnvironmentAsync(c, built, fields, cancellationToken);
        await CommandAsync(c, settings, fields, cancellationToken);
        if (settings.Stop is { } stop)
        {
            if (Quantity.Duration(stop) is not { } duration)
                Problem(c, "Stop: negative");
            else if (stop > TimeSpan.FromHours(1))
                Problem(c, $"Stop: {duration} is more than 1h");
            else
                fields["stop"] = duration;
        }

        // These fields say how the component takes its config.
        Configure(c, kind, fields);
        Config(c, settings, fields);

        // These fields say where a stateful component keeps its data, and how it is backed up.
        if (!built)
        {
            if (Volume(c, settings) is { } volume)
                fields["volume"] = volume;
            var backup = settings.Backup ?? resource switch
            {
                PostgresServerResource => new[] { "pg_dumpall", "-U", "postgres" },
                RedisResource => new[] { "sh", "-c", RedisBackup },
                _ => null,
            };
            if (backup is { Count: > 0 })
                fields["backup"] = Seq(backup);
        }

        // This field says how the component scales.
        if (settings.Scale is { } scale && Scale(c, settings, scale) is { } scaleMap)
            fields["scale"] = scaleMap;

        var entry = new YamlMap(YamlStyle.Block);
        foreach (var key in FieldOrder)
        {
            if (fields.TryGetValue(key, out var value))
                entry[key] = value;
        }
        return entry;
    }

    /// <summary>
    /// BuildAsync writes how a service, worker or task is built: from a project, or from a
    /// Dockerfile in the repository.
    /// </summary>
    private async Task<bool> BuildAsync(Component c, Dictionary<string, YamlNode> fields, CancellationToken cancellationToken)
    {
        var resource = c.Resource;
        var sources = new List<string>();
        var ok = true;
        if (resource.TryGetLastAnnotation<DockerfileBuildAnnotation>(out var dockerfileBuild))
        {
            var dockerfile = Path.GetFullPath(dockerfileBuild.DockerfilePath);
            var context = Path.GetFullPath(dockerfileBuild.ContextPath);
            if (dockerfileBuild.DockerfileFactory is not null || !File.Exists(dockerfile))
            {
                var where = PathUtil.IsInside(context, _root) ? Relative(context) : context;
                Problem(c, $"its Dockerfile is generated by Aspire when it publishes, so it isn't in the repository: add a Dockerfile to {where} and use AddDockerfile");
                return false;
            }
            foreach (var path in new[] { context, dockerfile })
            {
                if (!PathUtil.IsInside(path, _root))
                {
                    Outside(c, path);
                    return false;
                }
            }
            if (Path.GetFileName(dockerfile) != "Dockerfile")
            {
                Problem(c, $"its Dockerfile is {Relative(dockerfile)}: ProtoStrap builds the file called Dockerfile in a component's build directory");
                ok = false;
            }
            if (!string.IsNullOrEmpty(dockerfileBuild.Stage))
            {
                Problem(c, $"builds the stage {dockerfileBuild.Stage}: ProtoStrap builds a Dockerfile's last stage");
                ok = false;
            }
            if (dockerfileBuild.BuildArguments.Count > 0 || dockerfileBuild.BuildSecrets.Count > 0)
            {
                Problem(c, "build arguments aren't supported: ProtoStrap builds with none, so the image tag says everything about it");
                ok = false;
            }
            var build = Relative(Path.GetDirectoryName(dockerfile)!);
            var contextPath = Relative(context);
            fields["build"] = build;
            if (contextPath != build)
            {
                fields["context"] = contextPath;
                sources.Add(contextPath);
            }
            var (exclusions, warning) = DockerIgnore.Exclusions(context, dockerfile, _root);
            sources.AddRange(exclusions);
            if (warning is not null)
                _warnings.Add($"{c.Name}: {warning}");
        }
        else if (resource is ProjectResource project)
        {
            var path = Path.GetFullPath(project.GetProjectMetadata().ProjectPath);
            if (!PathUtil.IsInside(path, _root))
            {
                Outside(c, path);
                return false;
            }
            fields["project"] = Relative(path);
            try
            {
                c.Traced = await (_traces.TryGetValue(resource, out var trace) ? trace : _tracer.TraceAsync(path, cancellationToken));
                sources.AddRange(c.Traced.Paths);
            }
            catch (SourceTraceException e)
            {
                Problem(c, $"tracing its sources: {e.Message}");
                return false;
            }
            // ProtoStrap never picks a .NET SDK, so a new .NET needs no new ProtoStrap: the
            // deploy workflow installs the one global.json pins, which is among the sources, so
            // the image tag says which SDK built it.
            if (c.Traced.GlobalJson is null)
            {
                Problem(c, $"no global.json at or above {Relative(Path.GetDirectoryName(path)!)} pins the .NET SDK it builds with: add one that sets sdk.version");
                ok = false;
            }
            else if (c.Traced.SdkVersion is null)
            {
                Problem(c, $"{c.Traced.GlobalJson} doesn't pin the .NET SDK it builds with: set sdk.version");
                ok = false;
            }
        }
        else if (resource.TryGetLastAnnotation<ContainerImageAnnotation>(out var image))
        {
            Problem(c, $"runs the upstream image {ImageName(image)} without a Dockerfile: ProtoStrap builds every service, worker and task, so add a Dockerfile FROM it and use AddDockerfile");
            return false;
        }
        else
        {
            Problem(c, "isn't a project, a Dockerfile or a container: ProtoStrap can't build it");
            return false;
        }

        if (resource.TryGetLastAnnotation<ProtoStrapSourcesAnnotation>(out var declared))
        {
            foreach (var source in declared.Sources)
            {
                if (InsideRepository(source))
                    sources.Add(source);
                else
                    Problem(c, $"WithProtoStrapSources: \"{source}\" must be a relative path or pathspec inside the repository");
            }
        }
        if (sources.Count > 0)
            fields["sources"] = Seq(sources.Distinct().Order(StringComparer.Ordinal), YamlStyle.Block);
        return ok;
    }

    /// <summary>Image writes a stateful component's image: an upstream image, pinned.</summary>
    private bool Image(Component c, Dictionary<string, YamlNode> fields)
    {
        var resource = c.Resource;
        if (resource is ProjectResource)
        {
            Problem(c, "a stateful component runs an upstream image, pinned to a tag, not a project");
            return false;
        }
        if (resource.HasAnnotationOfType<DockerfileBuildAnnotation>())
        {
            Problem(c, "a stateful component runs an upstream image, pinned to a tag, not one built from a Dockerfile");
            return false;
        }
        if (resource is not ContainerResource || !resource.TryGetLastAnnotation<ContainerImageAnnotation>(out var image))
        {
            Problem(c, "a stateful component runs an upstream image, pinned to a tag");
            return false;
        }
        var name = ImageName(image);
        if (string.IsNullOrEmpty(image.SHA256) && (string.IsNullOrEmpty(image.Tag) || image.Tag == "latest"))
            Problem(c, $"image {name} must be pinned to a tag other than latest, or a digest");
        fields["image"] = name;
        return true;
    }

    private YamlMap? Request(Component c, ResourceSettings? request)
    {
        if (request is null)
        {
            Problem(c, "no request: call Request(cpu: ..., memory: ...)");
            return null;
        }
        var cpu = Quantity.Cpu(request.Cpu);
        if (cpu is null)
            Problem(c, $"Request: cpu \"{request.Cpu}\" isn't CPU, like \"500m\" or \"2\"");
        else if (cpu == "0m")
            Problem(c, "Request: cpu must be above 0");
        var memory = Quantity.Memory(request.Memory);
        if (memory is null)
            Problem(c, $"Request: memory \"{request.Memory}\" isn't memory, like \"512Mi\" or \"1Gi\"");
        else if (memory == "0Mi")
            Problem(c, "Request: memory must be above 0");
        return cpu is null || memory is null ? null : new YamlMap { ["cpu"] = cpu, ["memory"] = memory };
    }

    private YamlSeq? Routes(Component c, IReadOnlyList<RouteSettings> routes)
    {
        var items = new List<YamlNode>();
        foreach (var route in routes)
        {
            if (route.Route.Length == 0)
            {
                Problem(c, "Routes: an empty route");
                continue;
            }
            var host = route.Route.StartsWith('/') ? "" : route.Route.Split('/')[0];
            var path = host.Length == 0 ? route.Route : route.Route[host.Length..];
            if (host.Length > 0 && host.Contains('.'))
                Problem(c, $"Routes: a route names its host by its name, such as {environment.Hosts.Keys.Order(StringComparer.Ordinal).FirstOrDefault() ?? "app"}{(path.Length > 0 ? path : "/")}, not {host}");
            else if (host.Length > 0 && !environment.Hosts.ContainsKey(host))
                Problem(c, $"Routes: no host {host}: call WithHost(\"{host}\", ...)");
            if (route.Rate is not { } rate)
            {
                items.Add(route.Route);
            }
            else if (Quantity.Rate(rate) is { } perSecond)
            {
                items.Add(new YamlMap { ["route"] = route.Route, ["rate"] = perSecond });
            }
            else
            {
                Problem(c, $"Routes: the rate of {route.Route} must be above 0 requests per second");
            }
        }
        return items.Count > 0 ? new YamlSeq(items.ToArray()) : null;
    }

    /// <summary>
    /// Authorize writes the service that authorizes the component's requests at the edge, with
    /// the rules `protostrap check` applies.
    /// </summary>
    private YamlMap? Authorize(Component c, ComponentSettings settings, AuthorizeSettings authorize)
    {
        var ok = true;
        void Fail(string message)
        {
            Problem(c, "Authorize: " + message);
            ok = false;
        }
        if (settings.Routes.Count == 0)
            Fail("only a service with routes takes requests through the edge");
        var by = authorize.By;
        if (by.IsExcludedFromPublish())
            Fail($"{by.Name} is excluded from publish");
        else if (by == c.Resource)
            Fail("a service can't authorize its own requests");
        else if (!_components.TryGetValue(by, out var other) || other.Settings is null)
            Fail($"{by.Name} isn't a ProtoStrap component");
        else if (other.Settings.Kind != ComponentKind.Service)
            Fail($"{by.Name} is a {(other.Settings.Kind == ComponentKind.Stateful ? "stateful component" : other.Settings.Kind.ToString().ToLowerInvariant())}: only a service answers the edge");
        if (authorize.Path is { } path && !path.StartsWith('/'))
            Fail($"path \"{path}\" must start with /");
        foreach (var header in authorize.Headers.Concat(authorize.Forward))
        {
            if (!HeaderName().IsMatch(header))
                Fail($"\"{header}\" isn't a header name: lower case, such as x-user");
            else if (header is "host" or "content-length" or "transfer-encoding" or "connection" or "te" or "upgrade"
                or "x-forwarded-for" or "x-forwarded-proto" or "x-request-id" or "x-envoy-original-path")
                Fail($"the edge sets {header} itself");
        }
        // The edge frames the service's response on its own connection to the client: the
        // authorizer's content-length is its own body's, and HTTP/2 refuses a connection's headers.
        foreach (var header in authorize.Respond)
        {
            if (!HeaderName().IsMatch(header))
                Fail($"\"{header}\" isn't a header name: lower case, such as x-user");
            else if (header is "content-length" or "transfer-encoding" or "connection" or "keep-alive" or "proxy-connection" or "te" or "upgrade")
                Fail($"the edge sets {header} itself");
        }
        if (!ok)
            return null;
        var map = new YamlMap { ["by"] = by.Name };
        if (authorize.Path is { Length: > 0 } p && p != "/")
            map["path"] = p;
        if (authorize.Headers.Count > 0)
            map["headers"] = Seq(authorize.Headers);
        if (authorize.Forward.Count > 0)
            map["forward"] = Seq(authorize.Forward);
        if (authorize.Respond.Count > 0)
            map["respond"] = Seq(authorize.Respond);
        return map;
    }

    /// <summary>WaitFor is depends_on, and WaitForCompletion of a task is migrate.</summary>
    private void Waits(Component c, ComponentKind kind, Dictionary<string, YamlNode> fields)
    {
        var waits = c.Resource.Annotations.OfType<WaitAnnotation>().ToList();
        var dependsOn = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var wait in waits.Where(w => w.WaitType != WaitType.WaitForCompletion))
        {
            // A database belongs to its server's component.
            var target = wait.Resource;
            while (target is IResourceWithParent child)
                target = child.Parent;
            if (target == c.Resource || !_components.TryGetValue(target, out var other))
                continue;
            if (other.Settings?.Kind == ComponentKind.Task)
            {
                Problem(c, $"waits for {other.Name}, which is a task and never becomes ready: wait for its completion with WaitForCompletion");
                continue;
            }
            dependsOn.Add(other.Name);
        }
        if (dependsOn.Count > 0)
            fields["depends_on"] = Seq(dependsOn);

        var completions = waits.Where(w => w.WaitType == WaitType.WaitForCompletion)
            .Select(w => w.Resource)
            .Where(_components.ContainsKey)
            .Distinct()
            .Select(r => _components[r])
            .OrderBy(t => t.Name, StringComparer.Ordinal)
            .ToList();
        if (completions.Count == 0)
            return;
        var names = And(completions.Select(t => t.Name));
        if (completions.FirstOrDefault(t => _configuredBy.ContainsKey(t.Resource)) is { } configureTask)
        {
            var owner = _configuredBy[configureTask.Resource].Name;
            Problem(c, $"waits for the completion of {configureTask.Name}, which configures {owner} once it is ready: wait for {owner} with WaitFor, which waits for its configure task too");
        }
        else if (kind is not (ComponentKind.Service or ComponentKind.Worker))
            Problem(c, $"waits for the completion of {names}: only services and workers run a task as migrate");
        else if (completions.Count > 1)
            Problem(c, $"waits for the completion of {names}: ProtoStrap runs one task as a component's migrate");
        else if (completions[0].Settings is { Kind: not ComponentKind.Task } task)
            Problem(c, $"waits for the completion of {names}, which is a {task.Kind.ToString().ToLowerInvariant()}: only a task runs to completion");
        else
            fields["migrate"] = completions[0].Name;
    }

    /// <summary>
    /// EnvironmentAsync writes the component's environment, resolved in publish mode: literals in
    /// env, anything secret in secrets.
    /// </summary>
    private async Task EnvironmentAsync(Component c, bool built, Dictionary<string, YamlNode> fields, CancellationToken cancellationToken)
    {
        var resource = c.Resource;
        var values = new Dictionary<string, object>(StringComparer.Ordinal);
        try
        {
            var context = new EnvironmentCallbackContext(execution, resource, values, cancellationToken);
            foreach (var callback in resource.Annotations.OfType<EnvironmentCallbackAnnotation>())
                await callback.Callback(context);
        }
        catch (Exception e) when (e is not OperationCanceledException)
        {
            Problem(c, $"resolving its environment: {e.Message}");
            return;
        }

        // The integrations' passwords are secret parameters, which an upstream image can't read
        // from the environment's secret. So the agent writes them as files (SecretFiles), and the
        // variables that passed them are left out. PostgreSQL's socket inside its container
        // still trusts, for the backup and for the hook that applies a new password.
        switch (resource)
        {
            case PostgresServerResource:
                values.Remove("POSTGRES_USER");
                values.Remove("POSTGRES_PASSWORD");
                values["POSTGRES_PASSWORD_FILE"] = "/run/secrets/POSTGRES_PASSWORD";
                if (values.TryGetValue("POSTGRES_INITDB_ARGS", out var initdb) && initdb as string == "--auth-host=scram-sha-256 --auth-local=scram-sha-256")
                    values.Remove("POSTGRES_INITDB_ARGS");
                break;
            case RedisResource:
                values.Remove("REDIS_PASSWORD");
                break;
        }

        var env = new YamlMap(YamlStyle.Block);
        var secrets = new SortedSet<string>(StringComparer.Ordinal);
        var connectionDetails = ConnectionProperties(values);
        foreach (var key in values.Keys.Order(StringComparer.Ordinal))
        {
            if (SetByProtoStrap(key))
            {
                Problem(c, $"{key} is set by ProtoStrap in every replica");
                continue;
            }
            if (!EnvName().IsMatch(key))
            {
                Problem(c, $"\"{key}\" isn't a variable name");
                continue;
            }
            var rendered = connectionDetails.Contains(key) ? SecretValue.Instance : Render(values[key], key);
            switch (rendered)
            {
                case Literal literal:
                    env[key] = literal.Value;
                    break;
                case SecretValue when built || c.Settings is { SecretFiles: true }:
                    secrets.Add(key);
                    break;
                case SecretValue:
                    Problem(c, $"{key} holds a secret or a connection detail, which would be written into a plain environment variable: a stateful component runs an upstream image, which can't read its secret, so call SecretFiles() and read it from /run/secrets/{key}");
                    break;
                case Skipped skipped:
                    _warnings.Add($"{c.Name}: {key} is left out: {skipped.Reason}");
                    break;
                case Invalid invalid:
                    Problem(c, invalid.Problem);
                    break;
            }
        }
        if (env.Count > 0)
            fields["env"] = env;
        if (secrets.Count > 0)
            fields["secrets"] = Seq(secrets);
        if (c.Settings?.SecretPrefix is { } prefix)
            SecretPrefix(c, prefix, fields);
        SecretFiles(resource, fields);
        RequestedSecretFiles(c, fields);
    }

    // These are how PostgreSQL and Redis get their passwords from the environment's secret,
    // and take a new one in place (docs/secrets.md#postgresql-and-redis). Each is
    // one line, and reads the password from its file, never a command line.
    private const string PostgresHook = """printf '%s\n' '\set pw `cat /run/secrets/POSTGRES_PASSWORD`' "ALTER ROLE postgres PASSWORD :'pw';" | psql -X -q -v ON_ERROR_STOP=1 -U postgres -d postgres""";
    private const string RedisCommand = "exec docker-entrypoint.sh redis-server --requirepass \"$(cat /run/secrets/REDIS_PASSWORD)\"";
    private const string RedisHook = """for f in /run/secrets/REDIS_PASSWORD /run/secrets/previous/REDIS_PASSWORD; do [ -f "$f" ] && REDISCLI_AUTH="$(cat "$f")" redis-cli --no-auth-warning -x CONFIG SET requirepass </run/secrets/REDIS_PASSWORD | grep -qx OK && exit 0; done; exit 1""";
    private const string RedisBackup = """REDISCLI_AUTH="$(cat /run/secrets/REDIS_PASSWORD)" exec redis-cli --no-auth-warning --rdb -""";

    /// <summary>
    /// SecretFiles has the agent write PostgreSQL's or Redis's password to a file, from the
    /// environment's secret, and apply a new one with a hook rather than a restart.
    /// </summary>
    private static void SecretFiles(IResource resource, Dictionary<string, YamlNode> fields)
    {
        var (key, hook) = resource switch
        {
            PostgresServerResource => ("POSTGRES_PASSWORD", PostgresHook),
            RedisResource => ("REDIS_PASSWORD", RedisHook),
            _ => (null, null),
        };
        if (key is null || hook is null)
            return;
        fields["secrets"] = Seq([key]);
        fields["secret_files"] = YamlScalar.Bool(true);
        fields["on_secret_change"] = Seq(["sh", "-c", hook]);
    }

    /// <summary>
    /// RequestedSecretFiles has the agent write the component's keys to files when its
    /// PublishAsProtoStrap* call asked for them with SecretFiles, and says what a new value does
    /// (docs/secrets.md#secret-files).
    /// </summary>
    private void RequestedSecretFiles(Component c, Dictionary<string, YamlNode> fields)
    {
        if (c.Settings is not { SecretFiles: true } settings)
            return;
        if (!fields.ContainsKey("secrets"))
        {
            Problem(c, "SecretFiles: it has no keys for the agent to write: a secret parameter or a connection string in its environment is one");
            return;
        }
        fields["secret_files"] = YamlScalar.Bool(true);
        switch (settings.OnSecretChange)
        {
            case { Mode: { } mode }:
                fields["on_secret_change"] = mode;
                break;
            case { Command.Count: 0 }:
                Problem(c, "SecretFiles: the command to run on a new value is empty");
                break;
            case { Command: { } command }:
                fields["on_secret_change"] = Seq(command);
                break;
        }
    }

    /// <summary>
    /// ConnectionProperties returns the variables WithReference adds beside each
    /// ConnectionStrings__&lt;name&gt;, one per connection property, such as PROTOFAST_HOST and
    /// PROTOFAST_DATABASENAME. Each is a connection detail, so it goes to the secret even when its
    /// value holds nothing secret: moving the database to a managed service changes them all.
    /// </summary>
    private static HashSet<string> ConnectionProperties(Dictionary<string, object> values)
    {
        var names = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (key, value) in values)
        {
            if (value is not ConnectionStringReference reference || !key.StartsWith("ConnectionStrings__", StringComparison.Ordinal))
                continue;
            var prefix = key["ConnectionStrings__".Length..].Replace('-', '_').ToUpperInvariant();
            foreach (var property in reference.Resource.GetConnectionProperties())
                names.Add(prefix + "_" + property.Key.ToUpperInvariant());
        }
        return names;
    }

    /// <summary>
    /// SecretPrefix writes the prefix of the component's own keys, with the rules `protostrap
    /// check` applies (internal/secret).
    /// </summary>
    private void SecretPrefix(Component c, string prefix, Dictionary<string, YamlNode> fields)
    {
        if (!Prefix().IsMatch(prefix))
            Problem(c, $"SecretPrefix: \"{prefix}\" must be a capital letter, then letters and digits, then _, such as Api_");
        else if (prefix is "Shared_" or "Edge_" or "Reporter_")
            Problem(c, $"SecretPrefix: {prefix} is reserved: Shared_ keys are every component's, and Edge_ and Reporter_ are ProtoStrap's");
        else
            fields["secret_prefix"] = prefix;
    }

    /// <summary>
    /// Config writes the component's config files and how it takes new ones, with the rules
    /// `protostrap check` applies (docs/config.md).
    /// </summary>
    private void Config(Component c, ComponentSettings settings, Dictionary<string, YamlNode> fields)
    {
        var configs = c.Resource.Annotations.OfType<ProtoStrapConfigAnnotation>().ToList();
        if (configs.Count > 1)
        {
            Problem(c, $"WithProtoStrapConfig: called twice, for {And(configs.Select(x => x.Target))}: a component has one config directory");
            return;
        }
        if (configs.SingleOrDefault() is not { } config)
        {
            if (settings.OnConfigChange is not null)
                Problem(c, "OnConfigChange: it has no config files to change: call WithProtoStrapConfig(...)");
            return;
        }

        var ok = true;
        void Fail(string message)
        {
            Problem(c, "WithProtoStrapConfig: " + message);
            ok = false;
        }
        var from = config.Source.TrimEnd(Path.DirectorySeparatorChar);
        if (from == _root.TrimEnd(Path.DirectorySeparatorChar))
            Fail("the whole repository can't be config files: name a directory in it");
        else if (!PathUtil.IsInside(from, _root))
            Fail($"{from} is outside the repository, where protostrap.yaml is");
        else if (!Directory.Exists(from))
            Fail($"{Relative(from)} isn't a directory: config files come from a directory of the repository");

        var target = config.Target;
        var volume = settings.Volume?.Path;
        if (!target.StartsWith('/'))
            Fail($"\"{target}\" must be an absolute path in the container");
        else if (target.TrimEnd('/').Length == 0)
            Fail("can't be the root of the container");
        else if (Within(target, "/run/secrets") || Within("/run/secrets", target))
            Fail($"{target} would cover or sit in the secret files at /run/secrets");
        else if (volume is not null && (Within(target, volume) || Within(volume, target)))
            Fail($"{target} would cover or sit in the volume at {volume}");
        if (!ok)
            return;
        fields["config"] = new YamlMap { ["from"] = Relative(from), ["path"] = target.TrimEnd('/') };

        switch (settings.OnConfigChange)
        {
            case { Mode: { } mode }:
                fields["on_config_change"] = mode;
                break;
            case { Command.Count: 0 }:
                Problem(c, "OnConfigChange: the command to run on new files is empty");
                break;
            case { Command: { } command }:
                fields["on_config_change"] = Seq(command);
                break;
        }
    }

    private static bool Within(string path, string dir)
    {
        path = path.TrimEnd('/');
        dir = dir.TrimEnd('/');
        return path == dir || path.StartsWith(dir + "/", StringComparison.Ordinal);
    }

    /// <summary>Configure writes the task that configures the component once it is ready.</summary>
    private void Configure(Component c, ComponentKind kind, Dictionary<string, YamlNode> fields)
    {
        var configures = c.Resource.Annotations.OfType<ProtoStrapConfigureAnnotation>().ToList();
        if (configures.Count == 0)
            return;
        if (configures.Count > 1)
        {
            Problem(c, $"WithProtoStrapConfigure: called for {And(configures.Select(x => x.Task.Name))}: a component has one configure task");
            return;
        }
        var task = configures[0].Task;
        if (kind is not (ComponentKind.Service or ComponentKind.Worker or ComponentKind.Stateful))
        {
            Problem(c, "WithProtoStrapConfigure: only services, workers and stateful components are configured");
            return;
        }
        if (task.IsExcludedFromPublish())
        {
            Problem(c, $"WithProtoStrapConfigure: {task.Name} is excluded from publish");
            return;
        }
        if (!_components.TryGetValue(task, out var other))
        {
            Problem(c, $"WithProtoStrapConfigure: {task.Name} isn't a ProtoStrap component");
            return;
        }
        if (other.Settings is { Kind: not ComponentKind.Task } settings)
        {
            Problem(c, $"WithProtoStrapConfigure: {task.Name} is a {settings.Kind.ToString().ToLowerInvariant()}, not a task: a configure task is published with PublishAsProtoStrapTask");
            return;
        }
        if (_configuredBy.TryGetValue(task, out var owner) && owner != c)
        {
            Problem(c, $"WithProtoStrapConfigure: {task.Name} already configures {owner.Name}: each component has its own configure task");
            return;
        }
        fields["configure"] = task.Name;
    }

    /// <summary>CommandAsync writes the component's command: the callback's, or the AppHost's arguments.</summary>
    private async Task CommandAsync(Component c, ComponentSettings settings, Dictionary<string, YamlNode> fields, CancellationToken cancellationToken)
    {
        var resource = c.Resource;
        var command = settings.Command?.ToList();
        if (resource is RedisResource)
        {
            // Redis's arguments only pass its password, from a variable: it reads it from its
            // file instead.
            if (command is null)
                command = ["sh", "-c", RedisCommand];
            else
                _warnings.Add($"{c.Name}: a command of its own must start Redis with the password in /run/secrets/REDIS_PASSWORD, as the default does");
        }
        else if (command is null && resource.TryGetAnnotationsOfType<CommandLineArgsCallbackAnnotation>(out var callbacks))
        {
            var args = new List<object>();
            try
            {
                var context = new CommandLineArgsCallbackContext(args, resource, cancellationToken) { ExecutionContext = execution };
                foreach (var callback in callbacks)
                    await callback.Callback(context);
            }
            catch (Exception e) when (e is not OperationCanceledException)
            {
                Problem(c, $"resolving its arguments: {e.Message}");
                return;
            }
            command = [];
            for (var i = 0; i < args.Count; i++)
            {
                var what = $"argument {i + 1}";
                switch (Render(args[i], what))
                {
                    case Literal literal:
                        command.Add(literal.Value);
                        break;
                    case SecretValue:
                        Problem(c, $"{what} holds a secret or a connection detail, which can't be written into its command: pass it in an environment variable, which goes to its secret");
                        break;
                    case Skipped skipped:
                        Problem(c, $"{what} can't be written: {skipped.Reason}");
                        break;
                    case Invalid invalid:
                        Problem(c, invalid.Problem);
                        break;
                }
            }
        }
        if (command is { Count: > 0 })
            fields["command"] = Seq(command);
    }

    private YamlMap? Volume(Component c, ComponentSettings settings)
    {
        var resource = c.Resource;
        var volumes = resource.Annotations.OfType<ContainerMountAnnotation>().Where(m => m.Type == ContainerMountType.Volume).ToList();
        if (volumes.Count > 1)
        {
            Problem(c, $"{volumes.Count} volumes, at {And(volumes.Select(v => v.Target))}: a stateful component has one volume");
            return null;
        }
        if (settings.Volume is not { } volume)
        {
            Problem(c, "no volume: call Volume(size: ..., path: ...)");
            return null;
        }
        var size = Quantity.Size(volume.Size);
        if (size is null)
            Problem(c, $"Volume: size \"{volume.Size}\" isn't a whole number of GiB, like \"100Gi\"");
        var path = volume.Path ?? volumes.SingleOrDefault()?.Target ?? DataPath(resource);
        if (path is null)
            Problem(c, "Volume: no path: say where its data lives with Volume(size: ..., path: ...), or WithDataVolume()");
        else if (!path.StartsWith('/'))
            Problem(c, $"Volume: path \"{path}\" must be an absolute path in the container");
        if (volume.Iops is <= 0)
            Problem(c, "Volume: iops must be above 0");
        if (volume.Throughput is <= 0)
            Problem(c, "Volume: throughput must be above 0");
        if (size is null || path is null)
            return null;
        var map = new YamlMap { ["path"] = path, ["size"] = size };
        if (volume.Iops is { } iops)
            map["iops"] = YamlScalar.Number(iops);
        if (volume.Throughput is { } throughput)
            map["throughput"] = YamlScalar.Number(throughput);
        return map;
    }

    /// <summary>
    /// DataPath returns where PostgreSQL and Redis keep their data, which from PostgreSQL 18 is a
    /// directory up.
    /// </summary>
    private static string? DataPath(IResource resource)
    {
        switch (resource)
        {
            case RedisResource:
                return "/data";
            case PostgresServerResource:
                var tag = resource.TryGetLastAnnotation<ContainerImageAnnotation>(out var image) ? image.Tag ?? "" : "";
                var major = new string(tag.TakeWhile(char.IsAsciiDigit).ToArray());
                return major.Length > 0 && int.Parse(major, CultureInfo.InvariantCulture) < 18 ? "/var/lib/postgresql/data" : "/var/lib/postgresql";
            default:
                return null;
        }
    }

    private YamlMap? Scale(Component c, ComponentSettings settings, ScaleSettings scale)
    {
        var ok = true;
        void Fail(string message)
        {
            Problem(c, "Scale: " + message);
            ok = false;
        }

        if (scale.Min < 0)
            Fail($"min {scale.Min} is negative");
        if (scale.Max < 1)
            Fail($"max {scale.Max} must be at least 1");
        else if (scale.Max < scale.Min)
            Fail($"max {scale.Max} is below min {scale.Min}");

        var demand = new List<YamlNode>();
        foreach (var signal in scale.Demand)
        {
            switch (signal)
            {
                case CpuSignal cpu when Quantity.Percent(cpu.Target) is { } percent:
                    demand.Add(new YamlMap { ["cpu"] = percent });
                    break;
                case CpuSignal cpu:
                    Fail($"cpu {Number(cpu.Target)} must be above 0 and at most 1, such as 0.70");
                    break;
                case RequestsSignal requests:
                    if (Quantity.Rate(requests.PerSecond) is { } rate)
                        demand.Add(new YamlMap { ["requests"] = rate });
                    else
                        Fail("requests must be above 0 per second");
                    if (settings.Kind != ComponentKind.Service || settings.Routes.Count == 0)
                        Fail("a requests signal is counted by the gateway, so only a service with routes has one");
                    break;
                case QueueSignal queue:
                    var jobs = Quantity.Rate(queue.Rate);
                    if (jobs is null)
                        Fail($"the rate of {queue.Queue.Name} must be above 0 jobs per second");
                    var drain = queue.Drain > TimeSpan.Zero ? Quantity.Duration(queue.Drain) : null;
                    if (drain is null)
                        Fail($"the drain of {queue.Queue.Name} must be above 0");
                    if (queue.Queue.IsExcludedFromPublish())
                        Fail($"{queue.Queue.Name} is excluded from publish");
                    demand.Add(new YamlMap { ["queue"] = queue.Queue.Name, ["rate"] = jobs ?? "", ["drain"] = drain ?? "" });
                    break;
                case MetricSignal metric:
                    if (!MetricName().IsMatch(metric.Name))
                        Fail($"\"{metric.Name}\" isn't a metric name");
                    if (metric.Target <= 0 || !double.IsFinite(metric.Target))
                        Fail("the metric's target must be above 0");
                    if (settings.Metrics is null)
                        Fail("a metric signal needs Metrics(port: ...)");
                    demand.Add(new YamlMap { ["metric"] = metric.Name, ["target"] = YamlScalar.Number(metric.Target) });
                    break;
            }
        }

        var limits = new List<YamlNode>();
        foreach (var limit in scale.Limits)
        {
            if (limit.Replicas is { } replicas)
            {
                if (replicas < 0)
                    Fail($"a replicas limit of {replicas} is negative");
                limits.Add(new YamlMap { ["replicas"] = YamlScalar.Number(replicas) });
            }
            else
            {
                if (!MetricName().IsMatch(limit.Metric ?? ""))
                    Fail($"\"{limit.Metric}\" isn't a metric name");
                limits.Add(new YamlMap { ["metric"] = limit.Metric ?? "" });
            }
        }

        if (!ok)
            return null;
        var map = new YamlMap { ["min"] = YamlScalar.Number(scale.Min), ["max"] = YamlScalar.Number(scale.Max) };
        if (demand.Count > 0)
            map["demand"] = new YamlSeq(demand.ToArray());
        if (limits.Count > 0)
            map["limits"] = new YamlSeq(limits.ToArray());
        return map;
    }

    // This section renders values as they will be in a replica.

    private abstract record Rendered;

    private sealed record Literal(string Value) : Rendered;

    /// <summary>
    /// SecretValue is a value that holds a secret or a connection detail: it goes to the
    /// component's secret, never into the spec.
    /// </summary>
    private sealed record SecretValue : Rendered
    {
        public static readonly SecretValue Instance = new();
    }

    /// <summary>Skipped is a value that nothing in a replica answers: it is left out, with a warning.</summary>
    private sealed record Skipped(string Reason) : Rendered;

    private sealed record Invalid(string Problem) : Rendered;

    /// <summary>
    /// Render gives a value as it will be in a replica. Endpoints are the component's name on the
    /// overlay and its target port, from any network the AppHost resolves them on. Parameters,
    /// connection strings and the endpoints of anything with a connection string are secret, so
    /// moving PostgreSQL to RDS only changes the secret.
    /// </summary>
    private Rendered Render(object? value, string what)
    {
        switch (value)
        {
            case null:
                return new Literal("");
            case string text:
                return new Literal(text);
            case IResourceBuilder<IResource> builder:
                return Render(builder.Resource, what);
            case ParameterResource or ConnectionStringReference or IResourceWithConnectionString:
                return SecretValue.Instance;
            case EndpointReference endpoint:
                return Endpoint(endpoint, EndpointProperty.Url, what);
            case EndpointReferenceExpression property:
                return Endpoint(property.Endpoint, property.Property, what);
            case ReferenceExpression expression:
                return Expression(expression, what);
            case ProtoStrapEmailResource:
                return new Invalid($"{what}: pass email with WithReference, which lets the component send mail from its domains");
            case ProtoStrapQueueResource or ProtoStrapFilesResource or ProtoStrapBucketResource:
                return new Invalid($"{what}: pass a queue or a bucket with WithReference, which gives its replicas QUEUE_<NAME>_URL, BUCKET_<NAME> or FILES_BUCKET");
            case bool or IFormattable:
                return new Literal(Convert.ToString(value, CultureInfo.InvariantCulture) ?? "");
            case IValueWithReferences references when HoldsSecret(references, []):
                return SecretValue.Instance;
            default:
                return new Invalid($"{what}: ProtoStrap.Hosting can't write a {value.GetType().Name} into the spec");
        }
    }

    private static bool HoldsSecret(IValueWithReferences value, HashSet<object> seen)
    {
        foreach (var reference in value.References)
        {
            if (!seen.Add(reference))
                continue;
            if (reference is ParameterResource or ConnectionStringReference or IResourceWithConnectionString)
                return true;
            if (reference is IValueWithReferences nested && HoldsSecret(nested, seen))
                return true;
        }
        return false;
    }

    private Rendered Endpoint(EndpointReference endpoint, EndpointProperty property, string what)
    {
        var target = endpoint.Resource;
        if (target is IResourceWithConnectionString)
            return SecretValue.Instance;
        // Whatever network the AppHost resolves an endpoint on, which for a project is the
        // host's, every replica reaches every other on the overlay.
        if (target.IsExcludedFromPublish())
            return new Invalid($"{what} refers to {target.Name}, which is excluded from publish");
        if (!_components.TryGetValue(target, out var other))
            return new Invalid($"{what} refers to {target.Name}, which isn't a ProtoStrap component");
        var annotation = target.Annotations.OfType<EndpointAnnotation>().FirstOrDefault(a => a.Name == endpoint.EndpointName);
        if (annotation is null)
            return new Invalid($"{what} refers to {target.Name}'s {endpoint.EndpointName} endpoint, which it doesn't have");
        var port = annotation.TargetPort ?? (annotation == other.Primary ? other.Port : null);
        if (port is null)
            return new Skipped($"{target.Name}'s {endpoint.EndpointName} endpoint has no target port, so nothing in a replica listens on it");

        var host = target.Name;
        var portText = port.Value.ToString(CultureInfo.InvariantCulture);
        return new Literal(property switch
        {
            EndpointProperty.Host or EndpointProperty.IPV4Host => host,
            EndpointProperty.Port or EndpointProperty.TargetPort => portText,
            EndpointProperty.HostAndPort => $"{host}:{portText}",
            EndpointProperty.Scheme => annotation.UriScheme,
            EndpointProperty.TlsEnabled => annotation.TlsEnabled ? "true" : "false",
            _ => $"{annotation.UriScheme}://{host}:{portText}",
        });
    }

    private Rendered Expression(ReferenceExpression expression, string what)
    {
        if (expression.IsConditional)
        {
            return Render(expression.Condition, what) switch
            {
                Literal condition => Render(condition.Value == expression.MatchValue ? expression.WhenTrue : expression.WhenFalse, what),
                var other => other,
            };
        }
        var parts = expression.ValueProviders.Select(p => Render(p, what)).ToList();
        if (parts.OfType<SecretValue>().Any())
            return SecretValue.Instance;
        if (parts.OfType<Invalid>().FirstOrDefault() is { } invalid)
            return invalid;
        if (parts.OfType<Skipped>().FirstOrDefault() is { } skipped)
            return skipped;
        var values = parts.Cast<Literal>().Select(l => l.Value).ToList();
        return new Literal(Format(expression.Format, values, expression.StringFormats));
    }

    /// <summary>
    /// Format fills in a ReferenceExpression's format, which has {0} or {0:uri} for each value, and
    /// {{ and }} for braces.
    /// </summary>
    private static string Format(string format, IReadOnlyList<string> values, IReadOnlyList<string?> formats)
    {
        return Placeholder().Replace(format, match =>
        {
            if (match.Value == "{{")
                return "{";
            if (match.Value == "}}")
                return "}";
            var index = int.Parse(match.Groups["index"].Value, CultureInfo.InvariantCulture);
            var value = values[index];
            var specifier = match.Groups["format"].Success ? match.Groups["format"].Value : index < formats.Count ? formats[index] : null;
            return specifier == "uri" ? Uri.EscapeDataString(value) : value;
        });
    }

